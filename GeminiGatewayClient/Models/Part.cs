using System.Text.Json;
using System.Text.Json.Serialization;

namespace GeminiGatewayClient.Models;

/// <summary>
/// A single segment of a multi-part <see cref="Content"/> message (text, inline media, file reference, function call, or function response).
/// See <see href="https://ai.google.dev/api/caching#Part"/>.
/// </summary>
public sealed class Part
{
    /// <summary>
    /// Optional. Inline text content.
    /// </summary>
    [JsonPropertyName("text")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? Text { get; set; }

    /// <summary>
    /// Optional. Indicates whether this part contains model reasoning/thought summary rather than final output text.
    /// </summary>
    [JsonPropertyName("thought")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public bool? Thought { get; set; }

    /// <summary>
    /// Optional. Opaque signature for thought parts returned by thinking models during multi-turn tool use.
    /// Must be sent back unchanged in subsequent turns.
    /// </summary>
    [JsonPropertyName("thoughtSignature")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public string? ThoughtSignature { get; set; }

    /// <summary>
    /// Optional. Inline media bytes.
    /// </summary>
    [JsonPropertyName("inlineData")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public Blob? InlineData { get; set; }

    /// <summary>
    /// Optional. URI-based file reference.
    /// </summary>
    [JsonPropertyName("fileData")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public FileData? FileData { get; set; }

    /// <summary>
    /// Optional. Predicted function call requested by the model.
    /// </summary>
    [JsonPropertyName("functionCall")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public FunctionCall? FunctionCall { get; set; }

    /// <summary>
    /// Optional. Output of a function call returned to the model.
    /// </summary>
    [JsonPropertyName("functionResponse")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public FunctionResponse? FunctionResponse { get; set; }

    /// <summary>
    /// Optional. Video clipping and frame-rate metadata associated with media in this part.
    /// </summary>
    [JsonPropertyName("videoMetadata")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public VideoMetadata? VideoMetadata { get; set; }

    /// <summary>
    /// Optional. Code generated by the model that is meant to be executed.
    /// </summary>
    [JsonPropertyName("executableCode")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public ExecutableCode? ExecutableCode { get; set; }

    /// <summary>
    /// Optional. Result of executing the <see cref="ExecutableCode"/>.
    /// </summary>
    [JsonPropertyName("codeExecutionResult")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public CodeExecutionResult? CodeExecutionResult { get; set; }

    /// <summary>
    /// Gets or sets additional JSON properties not explicitly modeled by this type.
    /// </summary>
    [JsonExtensionData]
    public IDictionary<string, JsonElement>? ExtensionData { get; set; }

    /// <summary>
    /// <c>true</c> when no data, metadata, or extension field is set on this part.
    /// </summary>
    internal bool IsEmpty =>
        Text is null &&
        Thought is null &&
        ThoughtSignature is null &&
        InlineData is null &&
        FileData is null &&
        FunctionCall is null &&
        FunctionResponse is null &&
        VideoMetadata is null &&
        ExecutableCode is null &&
        CodeExecutionResult is null &&
        (ExtensionData is null || ExtensionData.Count == 0);

    /// <summary>
    /// Creates a text part.
    /// </summary>
    /// <param name="text">The text content.</param>
    /// <returns>A new <see cref="Part"/>.</returns>
    public static Part FromText(string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        return new Part { Text = text };
    }

    /// <summary>
    /// Creates an inline media part without copying the underlying byte array.
    /// Prefer <see cref="FromUri"/> (Files API) for payloads larger than about 20 MB.
    /// </summary>
    /// <param name="data">The raw media bytes.</param>
    /// <param name="mimeType">The IANA MIME type of <paramref name="data"/> (see <see cref="MimeTypes"/>).</param>
    /// <returns>A new <see cref="Part"/>.</returns>
    public static Part FromBytes(byte[] data, string mimeType)
    {
        ArgumentNullException.ThrowIfNull(data);
        ArgumentException.ThrowIfNullOrWhiteSpace(mimeType);
        return new Part { InlineData = new Blob { MimeType = mimeType, Data = data } };
    }

    /// <summary>
    /// Creates an inline media part. Prefer <see cref="FromUri"/> (Files API) for payloads larger than about 20 MB.
    /// </summary>
    /// <param name="data">The raw media bytes.</param>
    /// <param name="mimeType">The IANA MIME type of <paramref name="data"/> (see <see cref="MimeTypes"/>).</param>
    /// <returns>A new <see cref="Part"/>.</returns>
    public static Part FromBytes(ReadOnlySpan<byte> data, string mimeType)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(mimeType);
        return new Part { InlineData = new Blob { MimeType = mimeType, Data = data.ToArray() } };
    }

    /// <summary>
    /// Creates a file reference part (for example a Files API URI or a Cloud Storage URI).
    /// </summary>
    /// <param name="fileUri">The file URI.</param>
    /// <param name="mimeType">Optional IANA MIME type of the file.</param>
    /// <returns>A new <see cref="Part"/>.</returns>
    public static Part FromUri(string fileUri, string? mimeType = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(fileUri);
        return new Part { FileData = new FileData { FileUri = fileUri, MimeType = mimeType } };
    }

    /// <summary>
    /// Creates a function response part that returns the result of a <see cref="Models.FunctionCall"/> to the model.
    /// </summary>
    /// <param name="name">The name of the function that was called.</param>
    /// <param name="response">The function output as a JSON object.</param>
    /// <param name="id">The <see cref="FunctionCall.Id"/> of the call being answered, when the model provided one.</param>
    /// <returns>A new <see cref="Part"/>.</returns>
    public static Part FromFunctionResponse(string name, JsonElement response, string? id = null)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(name);
        return new Part { FunctionResponse = new FunctionResponse { Name = name, Response = response, Id = id } };
    }

    internal Part Clone()
    {
        var clone = (Part)MemberwiseClone();
        clone.InlineData = InlineData?.Clone();
        clone.FileData = FileData?.Clone();
        clone.FunctionCall = FunctionCall?.Clone();
        clone.FunctionResponse = FunctionResponse?.Clone();
        clone.VideoMetadata = VideoMetadata?.Clone();
        clone.ExecutableCode = ExecutableCode?.Clone();
        clone.CodeExecutionResult = CodeExecutionResult?.Clone();
        if (ExtensionData is not null)
        {
            clone.ExtensionData = new Dictionary<string, JsonElement>(ExtensionData, StringComparer.Ordinal);
        }

        return clone;
    }

    internal void Validate(string pathPrefix, string paramName)
    {
        if (IsEmpty)
        {
            throw new ArgumentException($"{pathPrefix} must have at least one field set.", paramName);
        }

        var dataFieldsSet =
            (Text is not null ? 1 : 0) +
            (InlineData is not null ? 1 : 0) +
            (FileData is not null ? 1 : 0) +
            (FunctionCall is not null ? 1 : 0) +
            (FunctionResponse is not null ? 1 : 0);

        if (dataFieldsSet > 1)
        {
            throw new ArgumentException(
                $"{pathPrefix} cannot set more than one primary data field (Text, InlineData, FileData, FunctionCall, FunctionResponse) on the same Part.",
                paramName);
        }

        if (InlineData is not null)
        {
            if (string.IsNullOrWhiteSpace(InlineData.MimeType))
            {
                throw new ArgumentException($"{pathPrefix}.InlineData.MimeType cannot be null or whitespace.", paramName);
            }

            if (InlineData.Data is null || InlineData.Data.Length == 0)
            {
                throw new ArgumentException($"{pathPrefix}.InlineData.Data cannot be null or empty.", paramName);
            }
        }

        if (FileData is not null && string.IsNullOrWhiteSpace(FileData.FileUri))
        {
            throw new ArgumentException($"{pathPrefix}.FileData.FileUri cannot be null or whitespace.", paramName);
        }

        if (FunctionCall is not null && string.IsNullOrWhiteSpace(FunctionCall.Name))
        {
            throw new ArgumentException($"{pathPrefix}.FunctionCall.Name cannot be null or whitespace.", paramName);
        }

        if (FunctionResponse is not null)
        {
            if (string.IsNullOrWhiteSpace(FunctionResponse.Name))
            {
                throw new ArgumentException($"{pathPrefix}.FunctionResponse.Name cannot be null or whitespace.", paramName);
            }

            if (FunctionResponse.Response is null)
            {
                throw new ArgumentException($"{pathPrefix}.FunctionResponse.Response cannot be null.", paramName);
            }
        }
    }
}
