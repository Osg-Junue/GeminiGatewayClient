using System.Text.Json.Serialization;
using GeminiAPIWrapper.Serialization;

namespace GeminiAPIWrapper.Configurations;

/// <summary>
/// Reason why a model stopped generating tokens for a candidate.
/// See <see href="https://ai.google.dev/api/generate-content#finishreason"/>.
/// </summary>
[JsonConverter(typeof(LenientStringEnumConverter<FinishReason>))]
public enum FinishReason
{
    /// <summary>
    /// Default value when the finish reason is unspecified.
    /// </summary>
    [JsonStringEnumMemberName("UNSPECIFIED")]
    Unspecified,

    /// <summary>
    /// Standard API value when the finish reason is unspecified (<c>FINISH_REASON_UNSPECIFIED</c>).
    /// </summary>
    [JsonStringEnumMemberName("FINISH_REASON_UNSPECIFIED")]
    FinishReasonUnspecified,

    /// <summary>
    /// Natural stop point of the model or a configured stop sequence was reached.
    /// </summary>
    [JsonStringEnumMemberName("STOP")]
    Stop,

    /// <summary>
    /// The maximum number of tokens specified in the request was reached.
    /// </summary>
    [JsonStringEnumMemberName("MAX_TOKENS")]
    MaxTokens,

    /// <summary>
    /// The response candidate was flagged for safety reasons.
    /// </summary>
    [JsonStringEnumMemberName("SAFETY")]
    Safety,

    /// <summary>
    /// The response candidate was flagged for recitation of training material.
    /// </summary>
    [JsonStringEnumMemberName("RECITATION")]
    Recitation,

    /// <summary>
    /// The response candidate was flagged for using an unsupported language.
    /// </summary>
    [JsonStringEnumMemberName("LANGUAGE")]
    Language,

    /// <summary>
    /// Token generation stopped because the content contained forbidden terms from a blocklist.
    /// </summary>
    [JsonStringEnumMemberName("BLOCKLIST")]
    BlockList,

    /// <summary>
    /// Token generation stopped for potentially containing prohibited content.
    /// </summary>
    [JsonStringEnumMemberName("PROHIBITED_CONTENT")]
    ProhibitedContent,

    /// <summary>
    /// Token generation stopped because the content potentially contained Sensitive Personally Identifiable Information (SPII).
    /// </summary>
    [JsonStringEnumMemberName("SPII")]
    Spii,

    /// <summary>
    /// The function call generated by the model is invalid or malformed.
    /// </summary>
    [JsonStringEnumMemberName("MALFORMED_FUNCTION_CALL")]
    MalformedFunctionCall,

    /// <summary>
    /// Token generation stopped because generated images violated safety policies.
    /// </summary>
    [JsonStringEnumMemberName("IMAGE_SAFETY")]
    ImageSafety,

    /// <summary>
    /// Model generated a tool call when no tools were enabled or expected.
    /// </summary>
    [JsonStringEnumMemberName("UNEXPECTED_TOOL_CALL")]
    UnexpectedToolCall,

    /// <summary>
    /// Unknown or uncategorized reason returned by the server (<c>OTHER</c>).
    /// </summary>
    [JsonStringEnumMemberName("OTHER")]
    Other,

    /// <summary>
    /// Fallback value used when the server returns a finish reason not yet defined in this version of the library.
    /// </summary>
    Unknown
}
